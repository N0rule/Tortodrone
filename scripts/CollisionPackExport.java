import java.io.*;
import java.nio.file.*;
import java.security.*;
import java.util.*;
import java.util.HexFormat;
import org.tortodrone.world.MapCollision;

/** Build-time conversion: static-collision.properties -> collision.bin, pinned to the scene hash. */
public final class CollisionPackExport {
    public static void main(String[] args) throws Exception {
        if (args.length != 1) throw new IllegalArgumentException("Usage: CollisionPackExport <map-folder|maps-root>");
        Path root = Path.of(args[0]);
        if (Files.isDirectory(root.resolve("native"))) { export(root); return; }
        int count = 0;
        try (var paths = Files.list(root)) {
            for (Path folder : paths.sorted().toList()) {
                if (!Files.isDirectory(folder) || !Files.isRegularFile(folder.resolve("native/static-collision.properties"))) continue;
                export(folder); count++;
            }
        }
        System.out.println("PASS: generated collision for " + count + " map(s)");
    }

    public static void export(Path folder) throws Exception {
        Path nativeDir = folder.resolve("native");
        Path legacy = nativeDir.resolve("map.properties");
        Path unified = nativeDir.resolve("metadata.properties");
        Path properties = Files.isRegularFile(legacy) ? legacy : unified;
        Path staticCollision = nativeDir.resolve("static-collision.properties");
        if (!Files.isRegularFile(properties)) throw new IOException("Missing map.properties or metadata.properties: " + folder);
        if (!Files.isRegularFile(staticCollision)) throw new IOException("Missing static-collision.properties: " + folder);
        var map = new Properties();
        try (var in = Files.newInputStream(properties)) { map.load(in); }
        boolean nativeMetadata = properties.equals(unified);
        String sceneHash = nativeMetadata ? map.getProperty("sha256.scene.dat") : map.getProperty("scene-sha256");
        if (sceneHash == null || !sceneHash.matches("[0-9a-f]{64}"))
            throw new IOException("Missing scene hash: " + folder);
        var collision = MapCollision.fromProperties(staticCollision);
        Path output = nativeDir.resolve("collision.bin");
        collision.write(output, sceneHash);
        if (nativeMetadata) {
            map.setProperty("sha256.static-collision.properties", digest(staticCollision));
            map.setProperty("sha256.collision.bin", digest(output));
        } else {
            map.setProperty("static-collision-sha256", digest(staticCollision));
            map.setProperty("collision-sha256", digest(output));
        }
        try (var out = Files.newOutputStream(properties)) { map.store(out, "Generated by CollisionPackExport"); }
        System.out.println("PASS: " + folder + " tiles=" + collision.tileCount()
            + " shapes=" + collision.shapeCount() + " bytes=" + Files.size(output));
    }

    private static String digest(Path file) throws Exception {
        var digest = MessageDigest.getInstance("SHA-256");
        try (var in = Files.newInputStream(file)) {
            byte[] buffer = new byte[65536];
            for (int read; (read = in.read(buffer)) > 0; ) digest.update(buffer, 0, read);
        }
        return HexFormat.of().formatHex(digest.digest());
    }
}
